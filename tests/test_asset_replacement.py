def test_procedural_synthetic_requires_asset_specific_generation_evidence():
    for row in _rows():
        if row["provenance"] == "PROCEDURAL_SYNTHETIC":
            evidence = " ".join(
                (row["provenance_source"], row["notes"])
            ).lower()
